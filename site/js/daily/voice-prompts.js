  function linesFor(record) {
    const lines = ["DAY " + record.day + " REVIEW SCOPE — " + record.title];
    record.domains.forEach((item, index) => {
      lines.push("", (index + 1) + ". " + item.label);
      [
        ["Foundation", item.foundationTopics],
        ["Mechanism", item.mechanismTopics],
        ["Clinical/operative application", item.applicationTopics],
        ["Synthesis/rescue", item.synthesisTopics]
      ].forEach(group => {
        lines.push(group[0] + ":");
        group[1].forEach(topic => lines.push("- " + topic));
      });
    });
    return lines;
  }

